#!/usr/bin/env bash
# E4 (page cache), M3 (docs/ext/cachesim.md): does a smaller page cache that is being turned over make write-back
# start before the 30 s expiry, and so cut a slowly written file into more extents? Q3-like batch files (hardware/
# readback_cpu.py: 64 inner + 64 outer files, 1,200 + 5,600 MiB, written at 56 MiB/s, interleaved 8 KiB appends),
# then one read-back pass without CPU work, all under numactl --membind=0. Cells (random order):
#   b0_r450   no balloon,  a paced reader of lineitem at 450 MiB/s during the writes (the page cache turns over)
#   b16_r450  16 GiB balloon on node 0, reader at 450
#   b24_r450  24 GiB balloon, reader at 450
#   b24_r0    24 GiB balloon, no reader (small cache, no turnover)
# Per cell: extents per file (filefrag), write-back bursts (iostat), read-back off-CPU time. Our own files only
# (BIG_ROOT/bench/spill, deleted by readback_cpu); lineitem read-only. The balloon is always released (pkill -x).
# Do not edit this file while the job runs.     src/setup/detach.sh cachesim-m3 queries/ext/cachesim/m3.sh  (~25 min)
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/../../.."
export PYTHONPATH="$PWD/src:$PWD"
PY=.venv/bin/python
BIG=$($PY -c "from tpch.config import load; print(load().BIG_ROOT)")
OUT=results/bench/$(date +%Y%m%d-%H%M%S)_cachesim_m3
mkdir -p "$OUT" "$BIG/bench/spill"
cc -O2 -Wall -o "$OUT/balloon" src/tpch/ext/cachesim/balloon.c
$PY - "$OUT/lineitem.list" <<'PY'
import sys
from pathlib import Path
from tpch.config import load
from tpch.ext.parallel.bench import lineitem_list
lineitem_list(load(), Path(sys.argv[1]))
PY
S_TIME_FORMAT=ISO iostat -x -t -y 1 sdb > "$OUT/iostat.log" &
IO=$!
cleanup() { sudo -n pkill -x balloon 2>/dev/null || true; kill "$IO" 2>/dev/null || true; }
trap cleanup EXIT
echo "== out $OUT"
sha256sum hardware/readback_cpu.py hardware/temp_spill.py src/tpch/ext/cachesim/*.py src/tpch/ext/cachesim/*.c
for c in $(printf '%s\n' b0_r450 b16_r450 b24_r450 b24_r0 | shuf); do
  B=${c%%_*}; B=${B#b}; R=${c#*_r}
  echo "== $c start $(date +%s.%N)"
  sudo -n sh -c 'sync; echo 3 > /proc/sys/vm/drop_caches'; sleep 3
  if [[ $B != 0 ]]; then
    sudo -n numactl --membind=0 "$OUT/balloon" "$B" > "$OUT/balloon_$c.out" &
    until grep -q ready "$OUT/balloon_$c.out" 2>/dev/null; do sleep 1; done
  fi
  grep -E "MemFree|FilePages|Mlocked" /sys/devices/system/node/node0/meminfo
  RD=""
  if [[ $R != 0 ]]; then
    numactl --cpunodebind=0 --membind=0 $PY -m tpch.ext.cachesim.reader "$OUT/lineitem.list" "$R" 125 > "$OUT/reader_$c.out" &
    RD=$!
  fi
  echo "== $c write $(date +%s.%N)"
  numactl --cpunodebind=0 --membind=0 $PY -m hardware.readback_cpu "$BIG/bench/spill" --out "$OUT" --tag "$c" \
    --dev sdb --batches 64 --inner 1200 --outer 5600 --rate 56 --cpu-us 0
  [[ -n "$RD" ]] && { wait "$RD" || true; cat "$OUT/reader_$c.out"; }
  sudo -n pkill -x balloon 2>/dev/null || true
  sleep 2
  echo "== $c end $(date +%s.%N)"
done
echo "== done $OUT"
